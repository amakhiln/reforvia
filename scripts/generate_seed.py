#!/usr/bin/env python3
"""Generate supabase/migrations/0002_seed_default_program.sql from the workout workbook.

Usage: python3 -I scripts/generate_seed.py <workbook.xlsx> <output.sql>
"""
import re
import sys
import openpyxl

DAY_NUM = {"monday": 1, "tuesday": 2, "wednesday": 3, "thursday": 4, "friday": 5, "saturday": 6, "sunday": 7}
# Tracker row name -> Exercise Guide name, where the two sheets word it differently
NAME_ALIASES = {"Moderate incline walk, bike or elliptical": "Moderate cardio"}
TEMPLATE_PROGRAM_ID = "00000000-0000-4000-8000-000000000001"


def q(value):
    if value is None:
        return "null"
    return "'" + str(value).replace("'", "''") + "'"


def parse_reps(text):
    """'8–12' -> (8, 12); '10–15 / side' -> (10, 15); '25–35 min' -> (25, 35)."""
    nums = [int(n) for n in re.findall(r"\d+", text)]
    low = nums[0] if nums else None
    high = nums[1] if len(nums) > 1 else low
    lowered = text.lower()
    per_side = "side" in lowered
    timed = "sec" in lowered or "min" in lowered
    return low, high, per_side, timed


def main(xlsx_path, out_path):
    wb = openpyxl.load_workbook(xlsx_path, data_only=True)
    tracker = wb["Weekly Tracker"]
    guide = wb["Exercise Guide"]

    # --- exercise guide, deduplicated by name (first occurrence wins) ---
    exercises = {}
    for row in list(guide.iter_rows(values_only=True))[1:]:
        day, name, muscles, purpose, form, mistakes, alternatives, video = row[:8]
        if not name or name in exercises:
            continue
        exercises[name] = dict(muscles=muscles, purpose=purpose, form=form, mistakes=mistakes,
                               alternatives=alternatives, video=video)

    # --- plan rows ---
    sessions = []          # ordered unique (day, session)
    plan = []              # (day, session, exercise, sets, reps_text)
    for row in list(tracker.iter_rows(values_only=True))[1:]:
        day, session, exercise, sets, reps = row[:5]
        if not exercise:
            continue
        exercise = NAME_ALIASES.get(exercise, exercise)
        key = (day, session)
        if key not in sessions:
            sessions.append(key)
        plan.append((day, session, exercise, int(sets), str(reps)))

    missing = sorted({p[2] for p in plan} - set(exercises))
    if missing:
        sys.exit(f"Exercises in tracker but missing from guide: {missing}")

    timed_names = set()
    for _, _, ex, _, reps in plan:
        if parse_reps(reps)[3]:
            timed_names.add(ex)

    out = []
    out.append("-- GENERATED by scripts/generate_seed.py from the workout workbook. Safe to re-run: guarded by ON CONFLICT / existence checks.\n")

    out.append("insert into public.exercises (owner_id, name, main_muscles, purpose, form_instructions, common_mistakes, alternatives, video_url, is_timed, source)\nvalues")
    lines = []
    for name, e in exercises.items():
        lines.append("  (null, {}, {}, {}, {}, {}, {}, {}, {}, 'curated')".format(
            q(name), q(e["muscles"]), q(e["purpose"]), q(e["form"]), q(e["mistakes"]),
            q(e["alternatives"]), q(e["video"]), "true" if name in timed_names else "false"))
    out.append(",\n".join(lines))
    out.append("on conflict (lower(name)) where owner_id is null do nothing;\n")

    out.append(f"insert into public.programs (id, user_id, name, is_template, is_active)\n"
               f"values ('{TEMPLATE_PROGRAM_ID}', null, 'V-Taper Split (Pull / Push / Legs / Upper)', true, true)\n"
               f"on conflict (id) do nothing;\n")

    # sessions
    out.append("insert into public.program_sessions (id, program_id, user_id, day_of_week, name, kind, is_optional, sort_order)\nvalues")
    sess_ids = {}
    lines = []
    for i, (day, session) in enumerate(sessions):
        sid = f"00000000-0000-4000-8000-0000000001{i:02d}"
        sess_ids[(day, session)] = sid
        base_day = day.split(" ")[0].lower()
        optional = "optional" in day.lower()
        kind = "cardio" if "cardio" in session.lower() else "strength"
        lines.append("  ('{}', '{}', null, {}, {}, '{}', {}, {})".format(
            sid, TEMPLATE_PROGRAM_ID, DAY_NUM[base_day], q(session), kind, "true" if optional else "false", i))
    out.append(",\n".join(lines))
    out.append("on conflict (id) do nothing;\n")

    # planned exercises (only insert if template has none yet, to keep re-runs idempotent)
    out.append("insert into public.planned_exercises (session_id, user_id, exercise_id, sort_order, planned_sets, rep_target, rep_min, rep_max, per_side, is_timed)")
    selects = []
    counters = {}
    for day, session, ex, sets, reps in plan:
        sid = sess_ids[(day, session)]
        counters[sid] = counters.get(sid, 0)
        low, high, per_side, timed = parse_reps(reps)
        selects.append(
            "select '{}'::uuid, null::uuid, e.id, {}, {}, {}, {}, {}, {}, {} from public.exercises e where e.owner_id is null and lower(e.name) = lower({})".format(
                sid, counters[sid], sets, q(reps), low if low is not None else "null",
                high if high is not None else "null", "true" if per_side else "false",
                "true" if timed else "false", q(ex)))
        counters[sid] += 1
    out.append("select * from (\n" + "\nunion all\n".join(selects) + "\n) as seed(session_id, user_id, exercise_id, sort_order, planned_sets, rep_target, rep_min, rep_max, per_side, is_timed)")
    out.append("where not exists (select 1 from public.planned_exercises p where p.session_id = '{}');\n".format(next(iter(sess_ids.values()))))

    out.append("-- Give any users who signed up before this seed ran their own copy of the program.\n"
               "select public.clone_default_program(u.id)\nfrom auth.users u\n"
               "where not exists (select 1 from public.programs p where p.user_id = u.id);\n")

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(f"{len(exercises)} exercises, {len(sessions)} sessions, {len(plan)} planned rows -> {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
